const frenchMonths: Record<string, string> = {
  January: "janvier", February: "février", March: "mars", April: "avril", May: "mai", June: "juin",
  July: "juillet", August: "août", September: "septembre", October: "octobre", November: "novembre", December: "décembre",
  Jan: "janv.", Feb: "févr.", Mar: "mars", Apr: "avr.", Jun: "juin", Jul: "juil.", Aug: "août",
  Sep: "sept.", Sept: "sept.", Oct: "oct.", Nov: "nov.", Dec: "déc.",
};
const englishMonthOrder = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"];

export function translateText(source: string, locale: AppLocale): string {
  if (locale === "en") return source;
  const exact = french[source];
  if (exact) return exact;
  if (source.endsWith(" *")) {
    const base = french[source.slice(0, -2)];
    if (base) return `${base} *`;
  }
  if (source.endsWith(" (optional)")) {
    const base = french[source.slice(0, -11)];
    if (base) return `${base} (facultatif)`;
  }
  for (const [pattern, format] of patterns) {
    const match = source.match(pattern);
    if (match) return format(...match.slice(1));
  }
  if (/\b\d{1,2} (?:Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|Sep(?:t(?:ember)?)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?) \d{4}\b/.test(source)) {
    return source.replace(/\b(January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Sept|Oct|Nov|Dec)\b/g, (month) => frenchMonths[month] ?? month);
  }
  if (/^€[\d,]+\.\d{2}$/.test(source)) {
    return new Intl.NumberFormat("fr-FR", { style: "currency", currency: "EUR" }).format(Number(source.slice(1).replaceAll(",", "")));
  }
  if (/^[\d,]+ km$/.test(source) && source.includes(",")) {
    return `${new Intl.NumberFormat("fr-FR").format(Number(source.slice(0, -3).replaceAll(",", "")))} km`;
  }
  if (/^\d{1,3}(?:,\d{3})+$/.test(source)) {
    return new Intl.NumberFormat("fr-FR").format(Number(source.replaceAll(",", "")));
  }
  const englishDate = source.match(/^(\d{1,2}) (\w+) (\d{4})(?:,? (\d{1,2}:\d{2}))?( UTC)?$/);
  if (englishDate) {
    const [, day, monthName, year, time, utc] = englishDate;
    const month = englishMonthOrder.indexOf(monthName.slice(0, 3).toLowerCase());
    if (month >= 0) {
      const date = new Date(Date.UTC(Number(year), month, Number(day)));
      const formatted = new Intl.DateTimeFormat("fr-FR", {
        day: "numeric", month: monthName.length > 4 ? "long" : "short", year: "numeric", timeZone: "UTC",
      }).format(date);
      return `${formatted}${time ? ` à ${time}` : ""}${utc ?? ""}`;
    }
  }
  if (/^Could not /.test(source)) return "Impossible d’effectuer cette opération. Réessayez.";
  if (/^Invalid |^Unexpected /.test(source)) return "Les données fournies sont invalides.";
  if (/ not found\.$/.test(source)) return "Élément introuvable.";
  return source;
}
